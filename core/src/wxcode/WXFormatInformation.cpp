// Columns are L, M, Q, H; fields are parity bytes, blocks, data bytes per block.
// clang-format off
static constexpr std::array<std::array<ECProfile, 4>, 4> EC_PROFILES = {{
	{{{10, 1, 28}, {13, 1, 25}, {18, 1, 20}, {24, 1, 14}}},
	{{{14, 1, 38}, {17, 1, 35}, {13, 2, 13}, {16, 2, 10}}},
	{{{20, 1, 46}, {23, 1, 43}, {16, 2, 17}, {21, 2, 12}}},
	{{{14, 1, 38}, {17, 1, 35}, {13, 2, 13}, {16, 2, 10}}},
}};
// clang-format on

bool DecodeFormat(uint32_t first, uint32_t second, FormatInformation& out)
{
	if (first >= (1U << FORMAT_COPY_BITS) || second >= (1U << FORMAT_COPY_BITS))
		return false;
	unsigned closest = 0;
	unsigned distance = FORMAT_COPY_BITS + 1;
	for (unsigned i = 0; i < FORMAT_WORDS.size(); ++i) {
		unsigned firstDistance = std::popcount(first ^ FORMAT_WORDS[i]);
		unsigned secondDistance = std::popcount(second ^ FORMAT_WORDS[i]);
		unsigned candidate = std::min(firstDistance, secondDistance);
		if (candidate < distance) {
			distance = candidate;
			closest = i;
		}
		if (!distance)
			break;
	}
	if (distance > 3)
		return false;
	out.version = (closest >> 7) & 3;
	out.ecBits = (closest >> 5) & 3;
	out.mask = closest & 31;
	out.distance = distance;
	return true;
}

uint32_t FormatWord(unsigned index)
{
	return index < FORMAT_WORDS.size() ? FORMAT_WORDS[index] : 0;
}

std::span<const uint32_t> VersionDataMask(unsigned version)
{
	return version < EC_PROFILES.size() ? std::span(DATA_MASKS).subspan(version * ANGULAR_ROWS, ANGULAR_ROWS)
										: std::span<const uint32_t>{};
}

unsigned VersionTotalCodewords(unsigned version)
{
	static constexpr std::array<unsigned, 4> count = {38, 52, 66, 52};
	return version < count.size() ? count[version] : 0;
}

unsigned VersionCounterCount(unsigned version)
{
	return VersionTotalCodewords(version) * 8;
}

const ECProfile* VersionEC(unsigned version, unsigned ecIndex)
{
	return version < EC_PROFILES.size() && ecIndex < EC_PROFILES[version].size() ? &EC_PROFILES[version][ecIndex] : nullptr;
}

// Angle and radius are grid indices, not image coordinates.
unsigned MaskBit(unsigned mask, unsigned angle, unsigned radius)
{
	if (angle >= ANGULAR_ROWS || radius >= RADIAL_CELLS)
		return 0;
	unsigned sum = angle + radius;
	unsigned product = angle * radius;
	unsigned halves = angle / 3 + radius / 2;
	switch (mask) {
	case 0: return ((sum & 1) ^ (angle >= 10 && angle <= 50)) ^ 1;
	case 1: return (sum % 3 == 0) ^ (angle < 51);
	case 2: return ((sum & 1) ^ ((angle & 3) != 0)) ^ 1;
	case 3: return ((sum & 1) ^ (angle % 3 != 0)) ^ 1;
	case 4: return ((angle & 1) ^ (sum % 3 == 0)) ^ 1;
	case 5: return ((sum & 1) ^ (radius > 4)) ^ 1;
	case 6: return (product % 6 == 0) ^ (angle % 3 != 0);
	case 7: return ((angle & 0x1ca) == 0) ^ (radius & 1);
	case 8: return (product / 3 & 1) ^ (angle % 3 == 0);
	case 9: return (sum % 3 == 0) ^ (angle % 3 != 0);
	case 10: return (radius & 1) ^ (angle < 51);
	case 11: return angle < 51;
	case 12: return (sum % 3 == 0) ^ ((angle & 3) != 0);
	case 13: return (~sum) & 1;
	case 14: return (product % 6 == 0) ^ (radius & 1);
	case 15: return (~halves) & 1;
	case 16: return ((angle / 3 & 1) ^ (sum % 3 == 0)) ^ 1;
	case 17: return (~(angle / 3 ^ radius)) & 1;
	case 18: return (halves ^ sum) & 1;
	case 19: return (product / 3 & 1) ^ (radius > 4);
	case 20: return ((halves & 1) ^ ((angle / 3) % 3 == 0)) ^ 1;
	case 21: return (sum & 1) ^ ((angle & 1) | (angle < 10) | (radius < 5));
	case 22: return (sum % 3 == 0) ^ ((angle / 3) % 3 == 0);
	case 23: return (halves & 1) ^ (angle % 3 != 0);
	case 24: return (sum & 1) ^ (angle < 10);
	case 25: return (sum / 3 & 1) ^ (angle % 3 == 0);
	case 26: return (halves & 1) ^ (angle < 10 || angle > 50);
	case 27: return (sum % 3 == 0) ^ (product % 6 == 0);
	case 28: return ((sum + product + product / 3) & 1) ^ ((angle & 3) == 0);
	case 29: return (~(product / 3)) & 1;
	case 30: return (halves & 1) ^ ((angle & 3) == 0);
	case 31: return ((sum + product + product / 3) ^ halves) & 1;
	default: return 0;
	}
}

